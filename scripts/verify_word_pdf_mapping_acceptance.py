#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Verify real Word COM/PDF mapping artifacts from the synthetic acceptance fixture."""
from __future__ import annotations

import argparse
import json
import unicodedata
from pathlib import Path
from typing import Any

import fitz

from co_reviewer.identity import sha256_file
from co_reviewer.revision_models import revision_ledger_from_mapping
from co_reviewer.word_pdf_mapper import _normalise_pdf_text


def _read_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"Cannot read JSON artifact {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"JSON artifact root must be an object: {path}")
    return value


def verify_word_pdf_mapping_acceptance(
    *,
    ledger_path: str | Path,
    mapping_dir: str | Path,
    response_markdown: str | Path,
    response_docx: str | Path,
    response_quality: str | Path,
) -> dict[str, Any]:
    ledger_file = Path(ledger_path).expanduser().resolve()
    out_dir = Path(mapping_dir).expanduser().resolve()
    ledger = revision_ledger_from_mapping(_read_json(ledger_file))
    ledger.validate_or_raise()

    map_file = out_dir / "response_location_map.json"
    location_map = _read_json(map_file)
    if location_map.get("generator") != "co-reviewer-word-pdf-mapper-v1":
        raise ValueError("Location map was not generated by the Microsoft Word COM mapper.")
    if location_map.get("revision_ledger_sha256") is None:
        raise ValueError("Location map is not bound to a RevisionLedger SHA-256.")

    if len(location_map.get("documents", [])) != 1:
        raise ValueError("Synthetic mapping acceptance must produce exactly one final document role.")
    document_row = location_map["documents"][0]
    if document_row.get("document") != "Manuscript" or document_row.get("reused") is not False:
        raise ValueError("Expected a fresh Word COM export of the synthetic Manuscript role.")
    if document_row.get("sequence_audit", {}).get("status") not in {"pass", "manual_review"}:
        raise ValueError("Word-native Figure/Table sequence audit did not pass or declare manual review.")

    output_docx = Path(document_row.get("output_file", "")).expanduser().resolve()
    output_pdf = Path(document_row.get("pdf_file", "")).expanduser().resolve()
    word_page_count = document_row.get("word_page_count")
    if not isinstance(word_page_count, int) or isinstance(word_page_count, bool) or word_page_count < 1:
        raise ValueError("Word COM returned an invalid final page count.")
    if not output_docx.is_file() or sha256_file(output_docx) != document_row.get("output_sha256"):
        raise ValueError("Word-final Clean DOCX is missing or its SHA-256 is stale.")
    if not output_pdf.is_file() or sha256_file(output_pdf) != document_row.get("pdf_sha256"):
        raise ValueError("Word-exported PDF is missing or its SHA-256 is stale.")

    quality_file = Path(document_row.get("quality_report_file", "")).expanduser().resolve()
    quality_report = _read_json(quality_file)
    if (
        sha256_file(quality_file) != document_row.get("quality_report_sha256")
        or quality_report.get("status") not in {"PASS", "PASS_WITH_WARNINGS"}
    ):
        raise ValueError("Final Clean DOCX/PDF quality report is missing, stale or failing.")

    with fitz.open(str(output_pdf)) as pdf:
        if pdf.page_count != word_page_count:
            raise ValueError(
                f"PDF page count {pdf.page_count} differs from Word COM page count {word_page_count}."
            )
        if not location_map.get("response_units"):
            raise ValueError("Word COM location map contains no mapped ResponseUnit.")
        map_rows = {
            row.get("response_unit_id"): row
            for row in location_map["response_units"]
            if isinstance(row, dict)
        }
        expected_unit_id = "RU-WORD-QA-COM-01"
        map_unit = map_rows.get(expected_unit_id)
        if not isinstance(map_unit, dict) or len(map_unit.get("final_locations", [])) != 1:
            raise ValueError("Expected exactly one Word COM location for the synthetic ResponseUnit.")
        mapped_location = map_unit["final_locations"][0]
        if (
            mapped_location.get("mapping_method") != "word_com"
            or mapped_location.get("document") != "Manuscript"
            or not all(
                isinstance(mapped_location.get(field), int)
                and not isinstance(mapped_location.get(field), bool)
                and mapped_location[field] >= 1
                for field in ("page", "line_start", "line_end")
            )
            or mapped_location.get("page") > pdf.page_count
        ):
            raise ValueError("Word COM returned an invalid or out-of-range page/line locator.")
        page_text = _normalise_pdf_text(pdf.load_page(mapped_location["page"] - 1).get_text("text"))
        operation = next(
            operation
            for patch in ledger.patches
            for operation in patch.operations
            if operation.operation_id == "WORD-QA-COM-OP1"
        )
        if _normalise_pdf_text(operation.location_phrase) not in page_text:
            raise ValueError("The Word-reported PDF page does not contain the mapped target phrase.")

    units = {unit.response_unit_id: unit for unit in ledger.response_units}
    unit = units.get(expected_unit_id)
    if (
        unit is None
        or unit.status != "location_mapped"
        or not unit.semantic_review_confirmed
        or len(unit.final_locations) != 1
        or unit.final_locations[0].mapping_method != "word_com"
        or Path(unit.location_map_file or "").expanduser().resolve() != map_file
        or unit.location_map_file_sha256 != sha256_file(map_file)
    ):
        raise ValueError("RevisionLedger does not retain the exact hash-bound Word COM location evidence.")

    markdown_path = Path(response_markdown).expanduser().resolve()
    response_docx_path = Path(response_docx).expanduser().resolve()
    response_quality_path = Path(response_quality).expanduser().resolve()
    for label, path in (
        ("Response Letter Markdown", markdown_path),
        ("Response Letter DOCX", response_docx_path),
        ("Response Letter quality report", response_quality_path),
    ):
        if not path.is_file():
            raise FileNotFoundError(f"{label} is missing: {path}")
    response_text = markdown_path.read_text(encoding="utf-8")
    if expected_unit_id not in response_text or f"Page {mapped_location['page']}" not in response_text:
        raise ValueError("Response Letter Markdown does not include the mapped synthetic response and page.")
    response_quality_report = _read_json(response_quality_path)
    if response_quality_report.get("status") not in {"PASS", "PASS_WITH_WARNINGS"}:
        raise ValueError("Response Letter DOCX quality report is failing.")

    return {
        "passed": True,
        "revision_ledger": str(ledger_file),
        "location_map": str(map_file),
        "document_role": document_row["document"],
        "final_clean_docx": str(output_docx),
        "final_pdf": str(output_pdf),
        "word_page_count": word_page_count,
        "pdf_page_count": pdf.page_count,
        "mapped_response_unit": expected_unit_id,
        "page": mapped_location["page"],
        "line_start": mapped_location["line_start"],
        "line_end": mapped_location["line_end"],
        "target_phrase_pdf_corroborated": True,
        "final_document_quality_status": quality_report["status"],
        "response_letter_markdown": str(markdown_path),
        "response_letter_docx": str(response_docx_path),
        "response_letter_quality_status": response_quality_report["status"],
        "response_unit_status": unit.status,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Verify Word COM pagination, PDF corroboration and Response Letter outputs."
    )
    parser.add_argument("--ledger", required=True)
    parser.add_argument("--mapping-dir", required=True)
    parser.add_argument("--response-markdown", required=True)
    parser.add_argument("--response-docx", required=True)
    parser.add_argument("--response-quality", required=True)
    args = parser.parse_args()
    result = verify_word_pdf_mapping_acceptance(
        ledger_path=args.ledger,
        mapping_dir=args.mapping_dir,
        response_markdown=args.response_markdown,
        response_docx=args.response_docx,
        response_quality=args.response_quality,
    )
    print("[WORD/PDF ACCEPTANCE] PASS")
    print(json.dumps(result, ensure_ascii=False, indent=2))
    print("[BOUNDARY] Synthetic mapping and Response Letter only; no real manuscript acceptance is implied.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
